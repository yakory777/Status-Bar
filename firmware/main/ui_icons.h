#pragma once
/*
 * Индикаторы в правом верхнем углу — на всех экранах (заставка, сцены, задача, сопряжение):
 *   батарея — зелёная > 50 %, оранжевая 21–50 %, красная ≤ 20 %; при зарядке — молния
 *             и бегущая заливка; без аккумулятора — пустой корпус и подпись «USB»;
 *   Wi-Fi   — точка и три дуги по уровню сигнала; без Wi-Fi — тусклый перечёркнутый веер;
 *   звук    — перечёркнутый динамик, пока звук выключен.
 */
#include "lvgl.h"

void ui_icons_create(lv_obj_t *parent, const lv_font_t *font);

/* Правый край блока и его вертикальный центр — в координатах экрана. */
void ui_icons_place(int32_t right, int32_t center_y);

/* Ширина блока — чтобы соседи могли подвинуться. */
int32_t ui_icons_width(void);

/* Поверх всего на верхнем слое (заставка и экран сопряжения тоже там). */
void ui_icons_to_front(void);

void ui_icons_set_opa(lv_opa_t opa);

/* Перечитать батарею, Wi-Fi и звук. Зовётся таймером изнутри, но можно и вручную. */
void ui_icons_refresh(void);

/* Цвета темы: основной (контур, «вкл»), тусклый (выключенные дуги) и подписи. */
void ui_icons_set_colors(lv_color_t on, lv_color_t off, lv_color_t text);
