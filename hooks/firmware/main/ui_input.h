#pragma once
/*
 * Кнопка на плате (по умолчанию BOOT, GPIO0).
 *   нажать          — разбудить экран; иначе переключить «сцена ↔ экран задачи»;
 *                     когда агент ждёт решения с кнопки — ОТКЛОНИТЬ
 *   удерживать 1,2 с — когда агент ждёт решения с кнопки — РАЗРЕШИТЬ;
 *                     иначе — включить/выключить звук
 *   нажать дважды   — следующая сцена ожидания для текущей темы
 * Разрешение — только долгим удержанием с полосой прогресса, чтобы случайное
 * касание не разрешило опасную команду.
 */
#include <stdbool.h>

#define UI_LONG_PRESS_MS   1200
#define UI_DOUBLE_CLICK_MS 320

void ui_input_init(void);

/* Сообщить о смене состояния кнопки (после антидребезга). Под замком UI. */
void ui_input_button(bool pressed);
